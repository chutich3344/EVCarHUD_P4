int main(void)
{
    int bad = 0;
    for (unsigned i = 0; i < sizeof V / sizeof V[0]; i++) {
        const vec_t *v = &V[i];
        xadas_frame_t f;
        bool ok = xadas_parse(v->b, v->n, &f);
        bool good = ok == (bool)v->ok;
        if (ok && good) good = f.state == v->st && f.level == v->lv && f.imperial == v->imp && f.test == v->test &&
                               f.speed == v->sp && f.dist == v->dist && f.min == v->min;
        char chip[24];
        int c = 0;
        if (ok) xadas_chip_text(&f, true, chip, sizeof chip, &c); else chip[0] = 0;
        printf("%-4s %-22s chip \"%s\" mau %d o %d\n", good ? "OK" : "SAI", v->name, chip, c, ok ? xadas_obs_level(&f) : -1);
        bad += !good;
    }
    printf("%s\n", bad ? "CO LOI" : "TAT CA DUNG");
    return bad != 0;
}
